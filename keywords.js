export function extractKeywords(text, limit = 25) {
    let words = text.toLowerCase().match(/[а-яёa-z0-9\.\-]{3,}/g) || [];

    words = words
        .map(w => w.replace(/^[.\-]+|[.\-]+$/g, ''))
        .filter(w => w.length >= 3)
        .filter(w => !/^[a-z0-9\-]+\.[a-z]{2,}$/.test(w))   // домены вида site.ru
        .filter(w => !/^\d+$/.test(w))                       // чистые числа
        .filter(w => !stopWords.has(w));

    const freq = {};
    for (const w of words) {
        freq[w] = (freq[w] || 0) + 1;
    }

    return Object.entries(freq)
        .sort((a, b) => b[1] - a[1])
        .slice(0, limit)
        .map(([word, count]) => ({ word, count }));
}